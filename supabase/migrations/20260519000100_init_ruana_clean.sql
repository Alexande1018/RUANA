create policy "profiles_select_self_or_admin"
on public.profiles for select
to authenticated
using (id = auth.uid() or public.is_ruana_admin());

create policy "aliados_select_self_or_admin"
on public.aliados for select
to authenticated
using (auth_user_id = auth.uid() or public.is_ruana_admin());

create policy "aliados_update_self_or_admin"
on public.aliados for update
to authenticated
using (auth_user_id = auth.uid() or public.is_ruana_admin())
with check (auth_user_id = auth.uid() or public.is_ruana_admin());

create policy "notificaciones_select_self_or_admin"
on public.notificaciones_aliado for select
to authenticated
using (aliado_codigo = public.current_aliado_codigo() or public.is_ruana_admin());

create policy "notificaciones_update_self_or_admin"
on public.notificaciones_aliado for update
to authenticated
using (aliado_codigo = public.current_aliado_codigo() or public.is_ruana_admin())
with check (aliado_codigo = public.current_aliado_codigo() or public.is_ruana_admin());

create policy "contactos_select_participants_or_admin"
on public.contactos_ruana for select
to authenticated
using (
  public.is_ruana_admin()
  or public.current_aliado_codigo() in (solicitante_codigo, profesional_codigo)
);

create policy "chat_select_participants_or_admin"
on public.chat_mensajes for select
to authenticated
using (
  public.is_ruana_admin()
  or exists (
    select 1
    from public.contactos_ruana c
    where c.id = chat_mensajes.contacto_id
      and public.current_aliado_codigo() in (c.solicitante_codigo, c.profesional_codigo)
  )
);

create policy "chat_insert_participants_or_admin"
on public.chat_mensajes for insert
to authenticated
with check (
  public.is_ruana_admin()
  or (
    emisor_codigo = public.current_aliado_codigo()
    and exists (
      select 1
      from public.contactos_ruana c
      where c.id = chat_mensajes.contacto_id
        and public.current_aliado_codigo() in (c.solicitante_codigo, c.profesional_codigo)
    )
  )
);

